const byId = new Map(STEAM_TAGS)
export const tagName = (id: number): string => byId.get(id) ?? `tag ${id}`

/** Prefix matches first, then anywhere in the name; popularity order within each. */
export function searchTags(query: string, exclude: readonly number[], limit = 8) {
  const q = query.trim().toLowerCase()
  const out = new Set(exclude)
  const pool = STEAM_TAGS.filter(([id]) => !out.has(id))
  if (!q) return pool.slice(0, limit)
  const starts = pool.filter(([, n]) => n.toLowerCase().startsWith(q))
  const within = pool.filter(
    ([, n]) => !n.toLowerCase().startsWith(q) && n.toLowerCase().includes(q),
  )
  return [...starts, ...within].slice(0, limit)
}
